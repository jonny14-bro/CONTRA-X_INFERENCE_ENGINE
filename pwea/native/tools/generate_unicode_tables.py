#!/usr/bin/env python3

import re
import regex
import unicodedata
from pathlib import Path

MAX_CP = 0x110000
ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "include" / "pwea_unicode_tables.h"

def make_ranges(predicate):
    ranges = []
    start = None

    for cp in range(MAX_CP):
        matched = predicate(cp)

        if matched and start is None:
            start = cp
        elif not matched and start is not None:
            ranges.append((start, cp - 1))
            start = None

    if start is not None:
        ranges.append((start, MAX_CP - 1))

    return ranges

def emit_ranges(name, ranges):
    entries = ",\n".join(
        f"    {{0x{lo:X}, 0x{hi:X}}}" for lo, hi in ranges
    )

    return (
        f"static const uint32_t {name}[][2] = {{\n"
        f"{entries}\n"
        f"}};\n"
        f"static const size_t {name}_N = {len(ranges)};\n\n"
    )

print("Python Unicode:", unicodedata.unidata_version)
print("Regex version:", regex.__version__)

if unicodedata.unidata_version != "16.0.0":
    raise RuntimeError("Unexpected Python Unicode database version")

if not hasattr(regex, "__version__"):
    raise RuntimeError("Unexpected regex implementation")

# Python's own definitions are used for these two properties.
word_re = re.compile(r"\w")
cased_re = regex.compile(r"\p{Cased}")
ignorable_re = regex.compile(r"\p{Case_Ignorable}")

print("Generating Python-compatible word ranges...")
word_ranges = make_ranges(
    lambda cp: bool(word_re.fullmatch(chr(cp)))
)

print("Generating Python-compatible whitespace ranges...")
space_ranges = make_ranges(
    lambda cp: chr(cp).isspace()
)

print("Generating Cased ranges...")
cased_ranges = make_ranges(
    lambda cp: bool(cased_re.fullmatch(chr(cp)))
)

print("Generating Case_Ignorable ranges...")
ignorable_ranges = make_ranges(
    lambda cp: bool(ignorable_re.fullmatch(chr(cp)))
)

print("Generating lowercase mappings...")
lower_entries = []
lower_data = []

for cp in range(MAX_CP):
    original = chr(cp)
    lowered = original.lower()

    if lowered != original:
        mapped = [ord(ch) for ch in lowered]
        lower_entries.append((cp, len(lower_data), len(mapped)))
        lower_data.extend(mapped)

def emit_lowercase():
    entries = ",\n".join(
        f"    {{0x{cp:X}, {offset}, {length}}}"
        for cp, offset, length in lower_entries
    )

    data = ",\n".join(
        "    " + ", ".join(f"0x{cp:X}" for cp in lower_data[i:i + 12])
        for i in range(0, len(lower_data), 12)
    )

    return (
        "struct LowerEntry {\n"
        "    uint32_t codepoint;\n"
        "    uint32_t offset;\n"
        "    uint8_t length;\n"
        "};\n\n"
        "static const LowerEntry LOWER_MAP[] = {\n"
        f"{entries}\n"
        "};\n"
        f"static const size_t LOWER_MAP_N = {len(lower_entries)};\n\n"
        "static const uint32_t LOWER_DATA[] = {\n"
        f"{data}\n"
        "};\n"
        f"static const size_t LOWER_DATA_N = {len(lower_data)};\n\n"
    )

content = (
    "// Generated by pwea/native/tools/generate_unicode_tables.py\n"
    f"// Python Unicode database: {unicodedata.unidata_version}\n"
    f"// regex version: {regex.__version__}\n"
    "// Do not edit manually.\n"
    "#pragma once\n"
    "#include <cstdint>\n"
    "#include <cstddef>\n\n"
)

content += emit_ranges("PY_WORD", word_ranges)
content += emit_ranges("PY_SPACE", space_ranges)
content += emit_ranges("UNICODE_CASED", cased_ranges)
content += emit_ranges("UNICODE_CASE_IGNORABLE", ignorable_ranges)
content += emit_lowercase()

OUTPUT.write_text(content, encoding="utf-8")

print("\nGeneration complete:")
print("Output:", OUTPUT)
print("PY_WORD ranges:", len(word_ranges))
print("PY_SPACE ranges:", len(space_ranges))
print("UNICODE_CASED ranges:", len(cased_ranges))
print("UNICODE_CASE_IGNORABLE ranges:", len(ignorable_ranges))
print("Lowercase entries:", len(lower_entries))
print("Lowercase output codepoints:", len(lower_data))
print("Header size:", OUTPUT.stat().st_size, "bytes")
